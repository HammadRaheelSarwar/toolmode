"use client";

import { useEffect, useMemo, useRef, useState } from "react";
import { Check, Copy, Download, FileArchive, FolderPlus, RotateCcw, ShieldCheck } from "lucide-react";

export type ResultFile = { blob: Blob; filename: string; mime: string };
export type ToolResult = {
  blob?: Blob;
  filename: string;
  mime: string;
  preview?: string;
  previewImageBlob?: Blob;
  files?: ResultFile[];
  alternatives?: ResultFile[];
  downloadAll?: Blob;
  downloadAllFilename?: string;
  title?: string;
  downloadLabel?: string;
  processingMode?: "local" | "server";
  notice?: string;
  comparison?: { originalSize: number; outputSize: number; savedBytes: number; savingsPercent: number; reduced: boolean };
  fileComparisons?: Array<{ filename: string; originalSize: number; outputSize: number; savingsPercent: number; reduced: boolean }>;
  editableText?: boolean;
  details?: Array<{ label: string; value: string }>;
};

function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function readableSize(bytes: number) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

export function ToolResults({ result, onStartOver, onSave, onTextChange, onRepeat }: { result: ToolResult; onStartOver: () => void; onSave?: () => void; onTextChange?: (value: string) => void; onRepeat?: () => void }) {
  const [copied, setCopied] = useState(false);
  const [previewUrl, setPreviewUrl] = useState("");
  const [editablePreview, setEditablePreview] = useState(result.preview || "");
  const textAreaRef = useRef<HTMLTextAreaElement>(null);
  const preview = result.editableText ? editablePreview : result.preview || "";
  const format = useMemo(() => result.filename.split(".").pop()?.toUpperCase() || "FILE", [result.filename]);
  const primaryBlob = result.editableText ? new Blob([preview], { type: "text/plain;charset=utf-8" }) : result.blob || result.files?.[0]?.blob;

  useEffect(() => { setEditablePreview(result.preview || ""); }, [result.preview, result.filename]);

  useEffect(() => {
    if (!result.previewImageBlob) { setPreviewUrl(""); return; }
    const url = URL.createObjectURL(result.previewImageBlob);
    setPreviewUrl(url);
    return () => URL.revokeObjectURL(url);
  }, [result.previewImageBlob]);

  async function copyResult() {
    if (!preview) return;
    try {
      await navigator.clipboard.writeText(preview);
    } catch {
      const input = document.createElement("textarea");
      input.value = preview; input.setAttribute("readonly", "");
      input.style.position = "fixed"; input.style.opacity = "0";
      document.body.appendChild(input); input.select();
      const copied = document.execCommand("copy"); input.remove();
      if (!copied) return;
    }
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1600);
  }

  return <div className="mt-6 rounded-2xl border border-line bg-pale p-5" aria-live="polite">
    <div className="flex flex-wrap items-start justify-between gap-3">
      <div className="flex items-start gap-3">
        <span className="flex h-9 w-9 items-center justify-center rounded-xl bg-ink text-white">
          <Check size={18}/>
        </span>
        <div>
          <p className="text-sm font-bold text-ink">{result.title || "Your result is ready"}</p>
          <p className="mt-1 text-xs text-muted">{result.filename} · {format}{primaryBlob ? ` · ${readableSize(primaryBlob.size)}` : ""}</p>
        </div>
      </div>
      <span className="inline-flex items-center gap-1.5 text-xs font-medium text-muted">
        <ShieldCheck size={14} className="text-ink"/>
        {result.processingMode === "server" ? "Generated by AI provider" : "Processed locally"}
      </span>
    </div>
    {result.details && <div className="mt-4 grid gap-2 rounded-xl border border-line bg-white p-3 text-sm sm:grid-cols-2">{result.details.map((item) => <div key={item.label} className="flex justify-between gap-3"><span className="text-xs font-medium text-muted">{item.label}</span><span className="font-semibold text-ink">{item.value}</span></div>)}</div>}
    {result.editableText ? <><textarea ref={textAreaRef} aria-label="Editable extracted PDF text" value={editablePreview} onChange={(event) => { setEditablePreview(event.target.value); onTextChange?.(event.target.value); }} className="mt-4 min-h-[260px] w-full resize-y rounded-xl border border-line bg-white p-4 font-mono text-sm leading-6 text-ink outline-none focus:border-ink focus:ring-1 focus:ring-ink"/><p className="mt-2 text-xs font-medium text-muted">{editablePreview.trim() ? editablePreview.trim().split(/\s+/).length : 0} words · {editablePreview.length} characters</p></> : preview && <pre className="mt-4 max-h-64 overflow-auto whitespace-pre-wrap rounded-xl border border-line bg-white p-4 font-mono text-sm leading-6 text-ink">{preview}</pre>}
    {previewUrl && <div className="mt-4 inline-block overflow-hidden rounded-xl border border-line bg-white shadow-xs"><img src={previewUrl} alt="Processed result preview" className="max-h-80 max-w-full object-contain rounded-lg"/></div>}
    {result.comparison && <div className="mt-4 grid gap-2 rounded-xl border border-line bg-white p-4 text-sm sm:grid-cols-2"><SizeStat label="Original size" value={readableSize(result.comparison.originalSize)}/><SizeStat label={result.comparison.savedBytes > 0 ? "Compressed size" : "Output size"} value={readableSize(result.comparison.outputSize)}/><SizeStat label={result.comparison.savedBytes > 0 ? "Space saved" : "Size change"} value={`${result.comparison.savedBytes > 0 ? "−" : "+"}${readableSize(Math.abs(result.comparison.savedBytes))}`}/><SizeStat label="Savings" value={`${result.comparison.savingsPercent.toFixed(1)}%`}/></div>}
    {result.fileComparisons && result.fileComparisons.length > 1 && <div className="mt-3 grid gap-2">{result.fileComparisons.map((item) => <div key={item.filename} className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-line bg-white p-3 text-xs"><span className="min-w-0 flex-1 truncate font-medium text-ink">{item.filename}</span><span className="text-muted">{readableSize(item.originalSize)} → {readableSize(item.outputSize)}</span><span className="font-semibold text-ink">{item.savingsPercent.toFixed(1)}%</span></div>)}</div>}
    {result.notice && <p className="mt-3 rounded-xl border border-line bg-white p-3 text-sm font-medium leading-6 text-ink">{result.notice}</p>}
    <div className="mt-4 flex flex-wrap gap-2">
      {primaryBlob && <button onClick={() => downloadBlob(primaryBlob, result.filename)} className="flex items-center gap-2 rounded-xl bg-ink px-4 py-2.5 text-sm font-medium text-white transition hover:bg-neutral-800"><Download size={15}/> {result.downloadLabel || (result.editableText ? "Download TXT" : `Download ${format}`)}</button>}
      {result.downloadAll && <button onClick={() => downloadBlob(result.downloadAll as Blob, result.downloadAllFilename || "toolmodeon-results.zip")} className="flex items-center gap-2 rounded-xl border border-line bg-white px-4 py-2.5 text-sm font-medium text-ink transition hover:bg-hover"><FileArchive size={15}/> Download all</button>}
      {onSave && <button onClick={onSave} className="flex items-center gap-2 rounded-xl border border-line bg-white px-4 py-2.5 text-sm font-medium text-ink transition hover:bg-hover"><FolderPlus size={15}/> Save to project</button>}
      {preview && <button onClick={copyResult} className="flex items-center gap-2 rounded-xl border border-line bg-white px-4 py-2.5 text-sm font-medium text-ink transition hover:bg-hover">{copied ? <Check size={15}/> : <Copy size={15}/>} {copied ? "Copied" : result.editableText ? "Copy Text" : "Copy"}</button>}
      {result.editableText && <><button onClick={() => textAreaRef.current?.select()} className="rounded-xl border border-line bg-white px-4 py-2.5 text-sm font-medium text-ink transition hover:bg-hover">Select All</button><button onClick={() => { setEditablePreview(""); onTextChange?.(""); }} className="rounded-xl border border-line bg-white px-4 py-2.5 text-sm font-medium text-ink transition hover:bg-hover">Clear Results</button>{onRepeat && <button onClick={onRepeat} className="rounded-xl border border-line bg-white px-4 py-2.5 text-sm font-medium text-ink transition hover:bg-hover">Extract Again</button>}</>}
      <button onClick={onStartOver} className="flex items-center gap-2 rounded-xl border border-transparent px-3 py-2.5 text-sm font-medium text-muted transition hover:text-ink hover:bg-hover"><RotateCcw size={15}/> Start over</button>
    </div>
    {result.files && result.files.length > 1 && <div className="mt-4 border-t border-line pt-4"><p className="text-xs font-bold uppercase tracking-wider text-ink">Individual files</p><div className="mt-2 grid gap-2 sm:grid-cols-2">{result.files.map((file) => <button key={file.filename} onClick={() => downloadBlob(file.blob, file.filename)} className="flex items-center justify-between gap-3 rounded-xl border border-line bg-white px-3 py-2 text-left text-xs font-medium text-ink transition hover:border-ink"><span className="truncate">{file.filename}</span><span className="shrink-0 text-muted">{readableSize(file.blob.size)}</span><Download className="shrink-0 text-ink" size={14}/></button>)}</div></div>}
    {result.alternatives && result.alternatives.length > 0 && <div className="mt-4 border-t border-line pt-4"><p className="text-xs font-bold uppercase tracking-wider text-ink">Alternative output</p><div className="mt-2 grid gap-2 sm:grid-cols-2">{result.alternatives.map((file) => <button key={file.filename} onClick={() => downloadBlob(file.blob, file.filename)} className="flex items-center justify-between rounded-xl border border-line bg-white px-3 py-2 text-left text-xs font-medium text-ink transition hover:border-ink"><span className="truncate">{file.filename}</span><Download className="ml-2 shrink-0 text-ink" size={14}/></button>)}</div></div>}
  </div>;
}

function SizeStat({ label, value }: { label: string; value: string }) { return <div className="flex items-center justify-between gap-3"><span className="text-xs font-semibold text-muted">{label}</span><span className="text-sm font-extrabold text-ink">{value}</span></div>; }
